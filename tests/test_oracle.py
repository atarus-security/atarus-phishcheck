"""Differential oracle: the tool's own header readers against the standard
library's parser under the default policy.

The default policy is too slow to run on hostile input of any size (that is
why the tool has its own readers), but on headers under ORACLE_CAP it is
affordable, and it is the reference for valid RFC 5322, 2045, 2047 and 2231
syntax. For every variant below, wherever the library extracts a sender
address and domain, a Reply-To address, an attachment file name or a
charset, the tool must extract the same value, or it must have raised a
malformed-header finding for that header. A divergence on a valid form is
a bug in the tool.

Variants: a hand-written list of valid and near-valid forms, plus a few
thousand generated by ``random.Random(SEED)``: comments, quoted pairs,
groups, display names with commas, encoded words, RFC 2231 continuations
and charsets, duplicate parameters, trailing separators and folding.
Standard library only.
"""
