def _sprinkle(rng: random.Random, text: str, junk: list) -> str:
    """Insert comments, spaces or folds at a few space or separator positions."""
    out = []
    for ch in text:
        out.append(ch)
        if ch in " ;,<>" and rng.random() < 0.25:
            choice = rng.random()
            if choice < 0.4:
                out.append(rng.choice(junk))
            elif choice < 0.7:
                out.append("\r\n ")
            else:
                out.append(" ")
    return "".join(out)


SPECIALS = list('<>@,;:"()\\[]=.') + ["\r\n ", " ", "\t"]


def _mutate(rng: random.Random, text: str) -> str:
    """For about 40% of variants: insert, delete or replace one to three
    characters with RFC 5322 and MIME specials, so near-valid shapes are
    covered as well as valid ones."""
    if rng.random() >= 0.4 or not text:
        return text
    chars = list(text)
    for _ in range(rng.randint(1, 3)):
        pos = rng.randrange(len(chars) + 1)
        op = rng.random()
        if op < 0.5:
            chars.insert(pos, rng.choice(SPECIALS))
        elif op < 0.75 and chars:
            del chars[min(pos, len(chars) - 1)]
        elif chars:
            chars[min(pos, len(chars) - 1)] = rng.choice(SPECIALS)
    return "".join(chars).strip("\r\n")


def _display(rng: random.Random) -> str:
    word = " ".join(rng.sample(WORDS, rng.randint(1, 2)))
    choice = rng.random()
    if choice < 0.3:
        return '"' + word.replace('"', '\\"') + '"'
    if choice < 0.45:
        return f"=?utf-8?b?{b64(word)}?="
    if choice < 0.55:
        return '"' + word + ", Inc.\""
    if choice < 0.65:
        return word + ", Inc."
    return word


def _mailbox(rng: random.Random) -> str:
    addr = rng.choice(LOCALS) + "@" + rng.choice(DOMAINS)
    choice = rng.random()
    if choice < 0.4:
        return f"{_display(rng)} <{addr}>"
    if choice < 0.55:
        return f"<{addr}>"
    if choice < 0.7:
        return f"{addr} {rng.choice(COMMENTS)}"
    if choice < 0.75:
        return f"<@relay.test:{addr}>"
    return addr


def address_variants(rng: random.Random, count: int) -> list:
    out = list(ADDRESS_FORMS)
    while len(out) < len(ADDRESS_FORMS) + count:
        boxes = [_mailbox(rng) for _ in range(rng.choice([1, 1, 1, 2, 3]))]
        value = ", ".join(boxes)
        choice = rng.random()
        if choice < 0.1:
            value = "undisclosed:;, " + value
        elif choice < 0.2:
            value = "Team: " + value + ";"
        if rng.random() < 0.15:
            value += rng.choice([",", ";", " ,", ", "])
        out.append(_mutate(rng, _sprinkle(rng, value, COMMENTS)))
    return out


PARAM_POOL = [
    'filename="{n}"', "filename={n}", "filename*=utf-8''{pct}", 'name="{n}"', "size=1234",
    'creation-date="Mon, 2 Nov 2026 10:00:00 +0000"', 'filename*0="{a}"; filename*1="{b}"',
    'filename="=?utf-8?b?{b64n}?="', "filename*0*=utf-8''{pa}; filename*1*={pb}",
]
NAMES = ["invoice.exe", "report.pdf", "a b.pdf", "résumé.docm", "photo.jpg.scr", "x;y.exe", 'q"t.exe']


def param_variants(rng: random.Random, count: int) -> list:
    from urllib.parse import quote
    out = list(PARAM_FORMS)
    while len(out) < len(PARAM_FORMS) + count:
        params = []
        for _ in range(rng.randint(1, 3)):
            name = rng.choice(NAMES)
            cut = rng.randint(1, len(name) - 1)
            template = rng.choice(PARAM_POOL)
            params.append(template.format(
                n=name.replace("\\", "\\\\").replace('"', '\\"'), pct=quote(name), a=name[:cut].replace('"', '\\"'), b=name[cut:].replace('"', '\\"'),
                b64n=b64(name), pa=quote(name[:cut]), pb=quote(name[cut:])))
        head = rng.choice(["attachment", "ATTACHMENT", "inline", "Attachment"])
        sep = rng.choice(["; ", ";", " ; ", ";\r\n "])
        value = head + sep + sep.join(params)
        if rng.random() < 0.15:
            value += rng.choice([";", "; ", ";;"])
        out.append(_mutate(rng, _sprinkle(rng, value, ["(c)", "(a;b)", "(x (y) z)", "( )"])))
    return out


def charset_variants(rng: random.Random, count: int) -> list:
    out = list(CHARSET_FORMS)
    charsets = ["utf-8", '"utf-8"', "UTF-8", "iso-8859-1", "koi8-r", "us-ascii", '"windows-1252"', "utf-16"]
    while len(out) < len(CHARSET_FORMS) + count:
        params = ["charset=" + rng.choice(charsets)]
        if rng.random() < 0.5:
            params.insert(rng.randint(0, 1), rng.choice(["format=flowed", 'name="a.txt"', "delsp=yes", "charset=" + rng.choice(charsets)]))
        value = rng.choice(["text/plain", "text/html", "TEXT/PLAIN"]) + "; " + "; ".join(params)
        out.append(_mutate(rng, _sprinkle(rng, value, ["(c)", "(a;b)", "( )"])))
    return out


def library(raw: bytes):
    return email.message_from_bytes(raw, policy=email.policy.default)


def text(value: str) -> str:
    """The library keeps 8-bit header bytes as surrogate escapes; the tool
    reads them as UTF-8. Same bytes, compared as the same text."""
    return value.encode("utf-8", "surrogateescape").decode("utf-8", "replace")


def _fits(raw: bytes) -> bool:
    return raw.index(b"\n\n") < ORACLE_CAP if b"\n\n" in raw else len(raw) < ORACLE_CAP


class AddressOracleTests(unittest.TestCase):
    def check_header(self, name: str, attr: str):
        rng = random.Random(SEED)
        checked = differed = 0
        failures = []
        for value in address_variants(rng, 1500):
            raw = (f"{name}: {value}\nTo: r@example.test\nSubject: x\n\nhi\n").encode("utf-8")
            if not _fits(raw):
                continue
            try:
                lib = [a for a in library(raw)[name].addresses if a.domain]
            except Exception:
                continue  # the library itself failed: nothing to compare
            if not lib:
                continue
            checked += 1
            headers, _body = parser.parse_email(raw)
            want_addr, want_domain = text(lib[0].addr_spec).lower(), text(lib[0].domain).lower()
            got_addr = getattr(headers, attr)
            got_domain = parser._domain_of(got_addr)
            if (got_addr, got_domain) != (want_addr, want_domain.rstrip(".")):
                differed += 1
                if not any(m["header"] == name for m in headers.malformed):
                    failures.append((value, want_addr, got_addr))
        self.assertGreater(checked, 1000)
        self.assertEqual(failures, [], f"{len(failures)} of {checked} differ from the library with no malformed finding")
        return checked, differed

    def test_from_matches_the_library_or_is_flagged(self):
        self.check_header("From", "from_email")

    def test_reply_to_matches_the_library_or_is_flagged(self):
        self.check_header("Reply-To", "reply_to_email")

    def test_flagged_from_headers_become_findings(self):
        result = pipeline.analyze_raw("From: support@paypal.example <service@evil.example>\nSubject: x\n\nhi\n", "x")
        self.assertIn(("Address headers are malformed", "medium"), [(f.title, f.severity) for f in result.findings])


class ParameterOracleTests(unittest.TestCase):
    def test_attachment_names_match_the_library_or_are_flagged(self):
        rng = random.Random(SEED + 1)
        checked = 0
        failures = []
        cases = [("application/octet-stream", cd) for cd in param_variants(rng, 1500)] + [(ct, None) for ct in CT_NAME_FORMS]
        for ctype, disposition in cases:
            raw = f"From: a@b.test\nMIME-Version: 1.0\nContent-Type: {ctype}\n"
            if disposition is not None:
                raw += f"Content-Disposition: {disposition}\n"
            raw = (raw + "\nAAAA\n").encode("utf-8")
            if not _fits(raw):
                continue
            try:
                want = library(raw).get_filename()
            except Exception:
                continue
            if not want or not want.strip():
                continue
            checked += 1
            _headers, body = parser.parse_email(raw)
            if not body.attachments:
                failures.append((disposition or ctype, want, None))
                continue
            att = body.attachments[0]
            names = [att["filename"]] + att["other_names"]
            if text(want).strip() not in names and not att["malformed"]:
                failures.append((disposition or ctype, want, names))
        self.assertGreater(checked, 1000)
        self.assertEqual(failures, [], f"{len(failures)} of {checked} differ from the library with no malformed finding")

    def test_charset_matches_the_library_or_is_flagged(self):
        rng = random.Random(SEED + 2)
        checked = 0
        failures = []
        for ctype in charset_variants(rng, 800):
            raw = f"From: a@b.test\nMIME-Version: 1.0\nContent-Type: {ctype}\n\nhi\n".encode("utf-8")
            if not _fits(raw):
                continue
            try:
                want = library(raw).get_content_charset()
            except Exception:
                continue
            if not want:
                continue
            checked += 1
            msg, _limited = parser._BoundedParse(raw).run()
            got = parser._part_charset(parser._params(parser._part_header(msg, "content-type")))
            _headers, body = parser.parse_email(raw)
            flagged = body.part_problems or any(a["malformed"] for a in body.attachments)  # a part that names a file is flagged on the attachment
            if got != want.lower() and not flagged:
                failures.append((ctype, want, got))
        self.assertGreater(checked, 500)
        self.assertEqual(failures, [], f"{len(failures)} of {checked} differ from the library with no malformed finding")


